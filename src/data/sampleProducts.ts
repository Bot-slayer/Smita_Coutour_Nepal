export const getFeaturedProducts = (): Product[] =>
  sampleProducts.filter((p) => p.isFeatured);

export const getNewArrivals = (): Product[] =>
  sampleProducts.filter((p) => p.isNew);

export const getSaleProducts = (): Product[] =>
  sampleProducts.filter((p) => p.isOnSale === true || p.isSale === true);

export const getProductsByCategory = (category: string): Product[] =>
  sampleProducts.filter(
    (p) => p.category === category || p.categoryLabel?.toLowerCase() === category.toLowerCase()
  );

export const getProductById = (id: string): Product | undefined =>
  sampleProducts.find((p) => p.id === id || p.slug === id);
